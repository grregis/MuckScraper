"""Regression cover for the Ollama default path against a real HTTP server.

Issue #8 phase 1 touched shared code -- generate_text, model_for_tier,
is_configured, check_llm_status, llm_status_detail, get_embedding -- not just
the OpenAI-compatible family. Every existing install runs LLM_PROVIDER=ollama
through exactly those functions, so "the cloud tests pass" says nothing about
whether the default path still works.

Uses a loopback server rather than the real Ollama box on purpose: an ad-hoc
probe during a pipeline run forces a model swap and contaminates the run's
timings (see TROUBLESHOOTING.md), and it would wake a suspended box for
nothing. This exercises the same requests stack without either cost.
"""

import json
import threading
import unittest
from http.server import BaseHTTPRequestHandler, HTTPServer
from unittest import mock

from news_fetcher import llm_client


class _FakeOllama(BaseHTTPRequestHandler):
    requests_seen = []

    def do_GET(self):
        # /api/tags is the reachability probe.
        payload = json.dumps({"models": [{"name": "nomic-embed-text"}]}).encode()
        self._respond(payload)

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(length) or b"{}")
        _FakeOllama.requests_seen.append({"path": self.path, "body": body})

        if self.path == "/api/generate":
            payload = json.dumps({"response": f"  generated by {body.get('model')}  "}).encode()
        elif self.path == "/api/embeddings":
            payload = json.dumps({"embedding": [0.1, 0.2, 0.3]}).encode()
        else:
            payload = b"{}"
        self._respond(payload)

    def _respond(self, payload):
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def log_message(self, *args):
        pass


class OllamaPathLoopbackTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.server = HTTPServer(("127.0.0.1", 0), _FakeOllama)
        cls.host = f"http://127.0.0.1:{cls.server.server_address[1]}"
        cls.thread = threading.Thread(target=cls.server.serve_forever, daemon=True)
        cls.thread.start()

    @classmethod
    def tearDownClass(cls):
        cls.server.shutdown()
        cls.server.server_close()

    def setUp(self):
        _FakeOllama.requests_seen = []
        llm_client._ollama_state["active"] = None
        llm_client._ollama_state["next_primary_probe"] = 0.0
        self._patchers = [
            mock.patch.object(llm_client, "LLM_PROVIDER", "ollama"),
            mock.patch.object(llm_client, "EMBEDDING_PROVIDER", "ollama"),
            mock.patch.object(llm_client, "OLLAMA_HOST", self.host),
            mock.patch.object(llm_client, "OLLAMA_FALLBACK_HOST", ""),
            mock.patch.object(llm_client, "OLLAMA_MODEL", "mistral-small:latest"),
            mock.patch.object(llm_client, "OLLAMA_FAST_MODEL", "llama3.1:8b"),
            mock.patch.object(llm_client, "EMBEDDING_MODEL", "nomic-embed-text"),
        ]
        for p in self._patchers:
            p.start()
        self.addCleanup(lambda: [p.stop() for p in self._patchers])

    def test_quality_tier_still_reaches_api_generate(self):
        result = llm_client.generate_text("summarize this", timeout=5)

        self.assertEqual(result, "generated by mistral-small:latest")
        seen = _FakeOllama.requests_seen[0]
        self.assertEqual(seen["path"], "/api/generate")
        self.assertEqual(seen["body"]["model"], "mistral-small:latest")
        self.assertEqual(seen["body"]["prompt"], "summarize this")
        self.assertIs(seen["body"]["stream"], False)

    def test_fast_tier_still_selects_the_fast_model(self):
        llm_client.generate_text("classify", timeout=5, tier=llm_client.TIER_FAST)

        self.assertEqual(_FakeOllama.requests_seen[0]["body"]["model"], "llama3.1:8b")

    def test_embeddings_still_work_and_stay_silent(self):
        # get_embedding() grew a warning branch in phase 1; the supported
        # providers must not trip it, and this runs per ingested article.
        with mock.patch.object(llm_client.logger, "warning") as warn:
            result = llm_client.get_embedding("some article text")

        self.assertEqual(result, [0.1, 0.2, 0.3])
        seen = _FakeOllama.requests_seen[0]
        self.assertEqual(seen["path"], "/api/embeddings")
        self.assertEqual(seen["body"]["model"], "nomic-embed-text")
        warn.assert_not_called()

    def test_status_and_config_gates_still_report_ollama(self):
        self.assertTrue(llm_client.is_configured())
        self.assertTrue(llm_client.check_llm_status())

        detail = llm_client.llm_status_detail()
        self.assertTrue(detail["online"])
        self.assertEqual(detail["provider"], "ollama")
        self.assertEqual(detail["host"], self.host)
        self.assertEqual(detail["role"], "primary")

    def test_unset_model_still_reads_as_not_configured(self):
        with mock.patch.object(llm_client, "OLLAMA_MODEL", ""):
            self.assertFalse(llm_client.is_configured())


if __name__ == "__main__":
    unittest.main()
